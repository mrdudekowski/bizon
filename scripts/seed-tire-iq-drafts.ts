const payload = await getPayload();

for (const draft of DRAFTS) {
  const existing = await payload.find({ collection: "tire-iq-articles", where: { slug: { equals: draft.slug } }, limit: 1, depth: 0 });
  const data = { ...draft, status: "draft" as const };

  if (existing.docs[0]) {
    await payload.update({ collection: "tire-iq-articles", id: existing.docs[0].id, data } as Parameters<Payload["update"]>[0]);
    console.log(`Updated draft: ${draft.slug}`);
  } else {
    await payload.create({ collection: "tire-iq-articles", data } as Parameters<Payload["create"]>[0]);
    console.log(`Created draft: ${draft.slug}`);
  }
}

