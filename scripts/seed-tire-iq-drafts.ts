type TextNode = {
  type: "text";
  detail: 0;
  format: 0;
  mode: "normal";
  style: "";
  text: string;
  version: 1;
};

function text(text: string): TextNode {
  return { type: "text", detail: 0, format: 0, mode: "normal", style: "", text, version: 1 };
}

function paragraph(value: string) {
  return { type: "paragraph" as const, format: "", indent: 0, version: 1, direction: "ltr" as const, children: [text(value)] };
}

function heading(value: string) {
  return { type: "heading" as const, tag: "h2" as const, format: "", indent: 0, version: 1, direction: "ltr" as const, children: [text(value)] };
}

function list(items: string[]) {
  return {
    type: "list" as const,
    listType: "bullet" as const,
    format: "",
    indent: 0,
    version: 1,
    direction: "ltr" as const,
    start: 1,
    tag: "ul" as const,
    children: items.map((item) => ({
      type: "listitem" as const,
      format: "",
      indent: 0,
      version: 1,
      direction: "ltr" as const,
      value: 1,
      children: [paragraph(item)],
    })),
  };
}

function documentContent(blocks: unknown[]) {
  return {
    root: { type: "root" as const, format: "", indent: 0, version: 1, direction: "ltr" as const, children: blocks },
  };
}

