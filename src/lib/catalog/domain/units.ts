export function kpaToBar(value: number): number {
  return value / 100;
}

export function kpaToPsi(value: number): number {
  return value * 0.1450377377;
}

export function kgToLb(value: number): number {
  return value * 2.2046226218;
}

export function mmToIn(value: number): number {
  return value / 25.4;
}
